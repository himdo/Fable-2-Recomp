#!/usr/bin/env python3
"""Find recompiled functions that continue another function's register state.

With non_volatile_as_local, every function keeps r14-r31 (and f14-f31,
v14-v31/v64-v127) in C++ locals; non_argument_as_local does the same for
r0/r2/r11/r12, f0 and v32-v63. That is only right for real functions, which
set those registers before using them. The analysis also splits off fragments
of functions - typically an epilogue reached by a tail branch (e.g.
TailCall_82238FCC, which loads the result through its parent's frame pointer
r31) - and those read the registers their parent left. In a fragment the local
starts at 0, so the game crashes (read of guest 0x64 at start-up) or worse.

This scans code generated with those flags and lists every function in which
some path from the entry reads such a local before assigning it (a
definite-assignment analysis over the generated control flow: labels, gotos,
if-blocks, switch tables). Stores of a register through ctx.r1 (the prologue
saving it) and hand-over lines don't count. The result goes into
share_registers_functions (fable2_share_registers.toml), so those functions
keep their registers in ctx and their callers hand theirs over through ctx.
Functions already listed keep no register locals, so a scan of code generated
with the current list reports only new ones (none, when the list is complete).

  find_register_fragments.py <generated dir> [--merge fable2_share_registers.toml]
                             [--list <out.txt>] [--show NAME]
"""
import os
import re
import sys

DEF_RE = re.compile(r"^DEFINE_REX_FUNC\((\w+)\) \{")
DECL_RE = re.compile(r"^\t(?:PPCRegister|double|PPCVRegister|PPCFRegister)\s+([rfv])(\d+)\{\};")
TOKEN_RE = re.compile(r"(?<![\w.])([rfv])(\d+)(?=\.|\s*[;,)])")
ASSIGN_RE = re.compile(r"^\s*([rfv])(\d+)(?:\.[\w]+(?:\[[^\]]*\])?)?\s*(=|[-+|&^*/]=|<<=|>>=)(?!=)")
STORE_RE = re.compile(r"^\s*simde_mm_store\w*\(\s*(?:\(simde__m128\w*\*\)\s*)?([fv])(\d+)\.")
LABEL_RE = re.compile(r"^(loc_[0-9A-Fa-f]+):")
GOTO_RE = re.compile(r"^\s*goto (loc_[0-9A-Fa-f]+);")
IFGOTO_RE = re.compile(r"^\s*if \(.*\) goto (loc_[0-9A-Fa-f]+);\s*$")
HANDOVER_RE = re.compile(r"^\s*(?:ho_([rfv]\d+) = ctx\.\1; )?ctx\.([rfv]\d+) = \2;\s*$")
MAP_RE = re.compile(r"\{\s*0x([0-9A-Fa-f]+),\s*(\w+)\s*\}")
ENTRY_RE = re.compile(r"0x([0-9A-Fa-f]{8}),\s*#\s*(\w+)")
MERGE_HEADER = """\
# Functions that continue another function's register state: split-off
# fragments (an epilogue reached by a tail branch, an entry point that gets a
# flag in r11) and functions the scan can't prove otherwise. They keep their
# registers in ctx, and callers with register locals hand theirs over around
# the call. Needed by non_volatile_as_local / non_argument_as_local; included
# from fable_2_manifest.toml.
#
# Generated by tools/find_register_fragments.py --merge (entries are only
# added). After a change to the code generator or the game's analysis: run the
# codegen, run the script on generated/default with --merge on this file, and
# rerun the codegen until the script finds nothing new.
"""


def reg_bit(kind, n):
    return n if kind == "r" else (32 + n if kind == "f" else 64 + n)


def bit_name(b):
    return f"r{b}" if b < 32 else (f"f{b - 32}" if b < 64 else f"v{b - 64}")


def nonvolatile_bit(b):
    if b < 64:
        return (b % 32) >= 14
    n = b - 64
    return 14 <= n <= 31 or 64 <= n <= 127


def brace_delta(line):
    s = re.sub(r'"(?:\\.|[^"\\])*"', "", line.split("//", 1)[0])
    return s.count("{") - s.count("}")


def analyse(lines):
    """Bitmask of local registers some path reads before assigning."""
    locals_mask = 0
    body = []
    for raw in lines:
        m = DECL_RE.match(raw)
        if m:
            locals_mask |= 1 << reg_bit(m.group(1), int(m.group(2)))
        else:
            body.append(raw)
    if not locals_mask:
        return 0
    n = len(body)
    labels = {}
    for i, raw in enumerate(body):
        m = LABEL_RE.match(raw)
        if m:
            labels[m.group(1)] = i
    # Per statement: reads, writes, successors.
    reads = [0] * n
    writes = [0] * n
    succ = [None] * n
    block_end = {}
    stack = []
    for i, raw in enumerate(body):
        code = raw.split("//", 1)[0]
        stripped = code.strip()
        d = brace_delta(code)
        if d > 0:
            for _ in range(d):
                stack.append(i)
        elif d < 0:
            for _ in range(-d):
                if stack:
                    block_end[stack.pop()] = i
    switch_cases = {}
    open_switch = []
    for i, raw in enumerate(body):
        stripped = raw.split("//", 1)[0].strip()
        if stripped.startswith("switch ("):
            open_switch.append(i)
            switch_cases[i] = []
        elif (stripped.startswith("case ") or stripped == "default:") and open_switch:
            switch_cases[open_switch[-1]].append(i)
        if open_switch and block_end.get(open_switch[-1]) == i:
            open_switch.pop()
    for i, raw in enumerate(body):
        code = raw.split("//", 1)[0]
        s = code.strip()
        nxt = [i + 1] if i + 1 < n else []
        if not s or LABEL_RE.match(raw):
            succ[i] = nxt
            continue
        m = GOTO_RE.match(code)
        if m:
            succ[i] = [labels[m.group(1)]] if m.group(1) in labels else []
            continue
        m = IFGOTO_RE.match(code)
        if m:
            succ[i] = nxt + ([labels[m.group(1)]] if m.group(1) in labels else [])
        elif s == "return;" or s.startswith("__builtin_trap") or s.startswith("REX_FATAL"):
            succ[i] = []
        elif s.startswith("switch ("):
            succ[i] = list(switch_cases.get(i, []))
        elif s.startswith("if (") and s.endswith("{") and i in block_end:
            e = block_end[i]
            succ[i] = nxt + ([e + 1] if e + 1 < n else [])
        else:
            succ[i] = nxt
        # Reads and writes of register locals.
        if "ctx.r1." in code and ("STORE" in code or "store" in code):
            continue  # prologue saving registers to the stack
        if HANDOVER_RE.match(code):
            continue  # hand-over to a shared-register function, not a use
        am = ASSIGN_RE.match(code)
        sm = STORE_RE.match(code)
        if am:
            w = reg_bit(am.group(1), int(am.group(2)))
            rhs = code[am.end():]
            if am.group(3) != "=":
                reads[i] |= 1 << w
        elif sm:
            w = reg_bit(sm.group(1), int(sm.group(2)))
            rhs = code[sm.end():]
        else:
            w = None
            rhs = code
        if s.startswith("if (") and IFGOTO_RE.match(code) is None and not s.endswith("{"):
            pass
        for k, num in TOKEN_RE.findall(rhs):
            b = reg_bit(k, int(num))
            if (locals_mask >> b) & 1:
                reads[i] |= 1 << b
        if w is not None and (locals_mask >> w) & 1:
            writes[i] |= 1 << w
    # Forward must-analysis: registers assigned on every path to each statement.
    full = locals_mask
    inn = [full] * n
    if n == 0:
        return 0
    inn[0] = 0
    work = [0]
    on = [False] * n
    on[0] = True
    while work:
        i = work.pop()
        on[i] = False
        out = inn[i] | writes[i]
        for j in succ[i]:
            v = inn[j] & out
            if v != inn[j] or j == 0 and False:
                inn[j] = v
                if not on[j]:
                    on[j] = True
                    work.append(j)
    # Statements never reached keep inn = full and report nothing.
    reached = [False] * n
    reached[0] = True
    stack2 = [0]
    while stack2:
        i = stack2.pop()
        for j in succ[i]:
            if not reached[j]:
                reached[j] = True
                stack2.append(j)
    live = 0
    for i in range(n):
        if reached[i]:
            live |= reads[i] & ~inn[i]
    return live & locals_mask


def iter_functions(gen):
    for fn in sorted(os.listdir(gen)):
        if not (fn.startswith("fable_2_recomp.") and fn.endswith(".cpp")):
            continue
        with open(os.path.join(gen, fn), encoding="utf-8", errors="replace") as f:
            lines = f.read().split("\n")
        i = 0
        while i < len(lines):
            m = DEF_RE.match(lines[i])
            if not m:
                i += 1
                continue
            j = i + 1
            while j < len(lines) and lines[j] != "}":
                j += 1
            yield m.group(1), lines[i + 1:j]
            i = j + 1


def main(argv):
    if not argv:
        sys.stderr.write(__doc__)
        return 1
    gen = argv[0]
    show = argv[argv.index("--show") + 1] if "--show" in argv else None
    addr_of = {}
    for fn in os.listdir(gen):
        if fn.endswith("_init.cpp"):
            with open(os.path.join(gen, fn), encoding="utf-8", errors="replace") as f:
                for a, name in MAP_RE.findall(f.read()):
                    addr_of.setdefault(name, int(a, 16))
    found = {}
    total = 0
    for name, body in iter_functions(gen):
        total += 1
        if show and name != show:
            continue
        live = analyse(body)
        if live:
            found[name] = live
    nv = {k: v for k, v in found.items() if any(nonvolatile_bit(b) for b in range(192) if (v >> b) & 1)}
    vol = {k: v for k, v in found.items() if any(not nonvolatile_bit(b) for b in range(192) if (v >> b) & 1)}
    missing = [n for n in found if n not in addr_of]
    print(f"{total} functions; {len(found)} read a local register before assigning it on some path "
          f"({len(nv)} a non-volatile, {len(vol)} a volatile one)"
          f"{f'; {len(missing)} without an address' if missing else ''}")
    for name in sorted(found)[:40] if not show else sorted(found):
        regs = ",".join(bit_name(b) for b in range(192) if (found[name] >> b) & 1)
        print(f"  {name}: {regs}")
    if "--list" in argv:
        out = argv[argv.index("--list") + 1]
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            for name in sorted(found):
                regs = ",".join(bit_name(b) for b in range(192) if (found[name] >> b) & 1)
                f.write(f"{name} {regs}\n")
    if "--merge" in argv:
        out = argv[argv.index("--merge") + 1]
        entries = {}
        if os.path.exists(out):
            with open(out, encoding="utf-8") as f:
                for a, name in ENTRY_RE.findall(f.read()):
                    entries[int(a, 16)] = name
        before = len(entries)
        for name in found:
            if name in addr_of:
                entries.setdefault(addr_of[name], name)
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(MERGE_HEADER + "\n")
            f.write("share_registers_functions = [\n")
            for a in sorted(entries):
                f.write(f"  0x{a:08X},  # {entries[a]}\n")
            f.write("]\n")
        print(f"{out}: {before} -> {len(entries)} functions")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
